SELECT * FROM mee_readings;

SELECT DATE, STEAM_FLOW_kghr, FEED_RATE_kLhr, PRODUCT_RATE_kghr, ANOMALY_FLAG
FROM mee_readings
ORDER BY STEAM_FLOW_kghr ASC;

SELECT DATE,
       (FEED_RATE_kLhr * 1000 - PRODUCT_RATE_kghr) AS EVAPORATION_LOAD_kghr,
       ROUND((FEED_RATE_kLhr * 1000 - PRODUCT_RATE_kghr) * 1.0 / STEAM_FLOW_kghr, 2) AS STEAM_ECONOMY
FROM mee_readings;

SELECT
    ROUND(AVG(STEAM_PRESSURE_kgcm2), 2) AS AVG_STEAM_PRESSURE,
    ROUND(AVG(VT04_OVERALL_VACUUM_mmHg), 2) AS AVG_OVERALL_VACUUM,
    ROUND(AVG(PRODUCT_CONC_PCT), 2) AS AVG_PRODUCT_CONC
FROM mee_readings;

SELECT DATE,
       CASE
           WHEN STEAM_FLOW_kghr < 500 THEN 'LOW_STEAM_FLOW_CHECK_INSTRUMENT'
           ELSE 'NORMAL'
       END AS FLOW_STATUS
FROM mee_readings;

SELECT DATE, PRODUCT_CONC_PCT - FEED_CONC_PCT AS CONCENTRATION_GAIN
FROM mee_readings
ORDER BY CONCENTRATION_GAIN DESC;
